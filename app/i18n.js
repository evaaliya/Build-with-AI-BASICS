const LANGS = [
  { code: 'ru', label: 'RU' },
  { code: 'ky', label: 'KY' },
  { code: 'en', label: 'EN' },
];

let currentLang = localStorage.getItem('moo_lang') || 'ru';

function t(key, vars) {
  const s = STRINGS[key];
  let str = (s && (s[currentLang] || s.en)) || key;
  if (vars) {
    Object.keys(vars).forEach((k) => { str = str.replace('{' + k + '}', vars[k]); });
  }
  return str;
}

function setLang(code) {
  currentLang = code;
  localStorage.setItem('moo_lang', code);
}

function getLang() { return currentLang; }

function applyI18n(scope) {
  const root = scope || document;
  root.querySelectorAll('[data-i18n]').forEach((el) => { el.textContent = t(el.dataset.i18n); });
  root.querySelectorAll('[data-i18n-ph]').forEach((el) => { el.placeholder = t(el.dataset.i18nPh); });
  root.querySelectorAll('[data-i18n-aria]').forEach((el) => { el.setAttribute('aria-label', t(el.dataset.i18nAria)); });
}


function plLang(n, oneKey, fewKey, manyKey) {
  const a = Math.abs(n) % 100, b = a % 10;
  const key = (a > 10 && a < 20) ? manyKey : b === 1 ? oneKey : (b > 1 && b < 5) ? fewKey : manyKey;
  return t(key);
}

export { t, setLang, getLang, applyI18n, LANGS, plLang };
